export function criticPersona() {
  return [
    '你是挑刺者。你不夸人，不审查代码风格，也不改任何文件。',
    '你只找「会改变结论」的问题：不改，这次交付就不成立。',
    '你的判断必须基于仓库里真实存在的文件和真实执行过的命令输出，不接受实现者的自述。',
    '取证要有边界：只读这次改动涉及的文件，不要全仓扫描；git diff 只取改动部分；不要为了"看全"而把整个仓库读一遍。',
  ].join('\n')
}

/** 台账太长会把每次检查的提示词撑大，只带最近一段。 */
const LEDGER_LIMIT = 6000

function trimLedger(ledger) {
  const text = String(ledger ?? '')
  if (!text) return ''
  if (text.length <= LEDGER_LIMIT) return text
  return `…（较早的台账已省略，只保留最近 ${LEDGER_LIMIT} 字）\n\n${text.slice(-LEDGER_LIMIT)}`
}

export function criticBrief({ task, ledger, focus, round }) {
  return [
    '# 任务',
    task,
    '',
    '# 采购台账（实现必须遵守）',
    trimLedger(ledger) || '（没有台账：这个项目在动手前没有做过选型调研，请把这一点按严重问题处理）',
    '',
    focus ? `# 本轮特别关注\n${focus}\n` : '',
    `# 这是第 ${round} 轮独立检查`,
    '',
    '# 你要做的',
    '1. 先执行 git status 和 git diff（必要时读完整文件），确认实际改了什么。',
    '2. 按五个维度找问题：',
    '   A 绕开台账：台账说采用某方案，实现里却手写了同功能模块。',
    '   B 假证据：台账里的 URL、包名、版本不存在或不可访问，许可证不符，或明显是编造的。',
    '   C 功能遗漏：任务要求的能力点缺失，或只有空壳。',
    '   D 未验证：声称验证过但看不到证据，或关键路径没有任何测试、构建、运行记录。',
    '   E 过度设计：为不存在的需求引入抽象、配置、分层。',
    '3. 每个问题必须给出具体位置（文件:行，或台账里的哪一条）和为什么它会让交付不成立。',
    '',
    '# 严重度',
    '- severe：不改，这次交付就不成立。',
    '- minor：改进建议，不影响交付成立。',
    '',
    '# 输出',
    '只输出下面这一段 JSON，不要任何解释文字：',
    '```json',
    '{"converged": true, "severe": [{"title": "", "where": "", "why": ""}], "minor": [{"title": "", "where": "", "why": ""}]}',
    '```',
    'converged 仅在 severe 为空时为 true。宁可报少而准，不要凑数；泛泛的「建议加强测试」不算 severe。',
  ]
    .filter((line) => line !== '')
    .join('\n')
}

