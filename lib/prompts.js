/** 追问一：还有没有没被覆盖到的地方。与挑刺分开问，避免它只是复述已有发现。 */
export function omissionBrief({ task, findings }) {
  return [
    '# 任务',
    task,
    '',
    '# 已经发现的问题（不要重复，不要评价它们）',
    findings || '（上一轮没有发现问题）',
    '',
    '# 你只回答一个问题',
    '这次实现里，还有什么是**没有被上面这些检查覆盖到**的？具体指：',
    '- 哪些文件、目录、入口根本没被看过；',
    '- 哪些需求点没有被验证过；',
    '- 哪些结论只有实现者的说法、拿不出证据。',
    '每条给出位置，以及为什么那里可能藏着问题。',
    '',
    '# 输出',
    '只输出这一段 JSON，不要解释：',
    '```json',
    '{"omissions": [{"title": "", "where": "", "why": ""}]}',
    '```',
    '确实没有遗漏时输出 {"omissions": []}。',
  ].join('\n')
}

/** 追问二：哪些判断是有把握的。与遗漏分开问，避免两者互相稀释。 */
